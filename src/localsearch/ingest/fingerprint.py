@dataclass
class SizeIndex:
    """尺寸的直方图：`尺寸 → 条数`。回答"哪些尺寸有同尺寸兄弟"。

    为什么只有计数、没有路径，见模块文档第 4 节——**这是 SQL 那一步的形状**，
    内存只要"不同尺寸"那么多。

    用法是流式的：扫描回调里 `add(entry.size)`，扫完再问 `duplicate_sizes()`。
    流式这件事不是风格问题：`C:` 盘 347 万条目（`E11`），攒下来就先输了。
    """

    counts: dict[int, int] = field(default_factory=dict)

    def add(self, size: int) -> None:
        """记一条。**尺寸为 0 的也记**：两个空文件是同一份内容，去重该折叠它们。"""
        self.counts[size] = self.counts.get(size, 0) + 1

    def add_all(self, sizes: Iterable[int]) -> None:
        for size in sizes:
            self.add(size)

    @property
    def files_seen(self) -> int:
        return sum(self.counts.values())

    @property
    def sizes_seen(self) -> int:
        return len(self.counts)

    def duplicate_sizes(self) -> set[int]:
        """有同尺寸兄弟的那些尺寸。**判据是 `> 1`，不是 `>= 2`**——同一个意思，
        写成 `> 1` 是因为它一眼就能读出"多出来一个才算兄弟"。"""
        return {size for size, n in self.counts.items() if n > 1}

    def needs_hash(self, size: int) -> bool:
        """这个尺寸的文件要不要算内容哈希。

        ⚠ **只在这一轮扫完之后调**。扫到一半时"还没有兄弟"与"永远没有兄弟"分不开，
        提前调会把先出现的那个文件判成"独一"而跳过——**那个文件正是重复对的第一个**。
        这个坑没有异常、没有日志，只是少了一对重复。所以判据挂在"扫完之后"这个用法
        上，而不是让 `add()` 顺手返回点什么。
        """
        return self.counts.get(size, 0) > 1

    def summary(self) -> dict[str, int]:
        """给报表用的几个数：条数、字节数、要哈希的条数与字节数。

        **按字节那一栏才是这条预筛真正的收益**（模块文档第 3 节）：`D:/work` 上
        要哈希的**条数占 96.5%**、而**字节只占 25.0%**。只报条数会让人以为这条预筛
        没用，只报字节会让人以为它把文件数也降下来了——两个都得给。
        """
        dup = self.duplicate_sizes()
        files = self.files_seen
        bytes_all = sum(size * n for size, n in self.counts.items())
        files_dup = sum(n for size, n in self.counts.items() if size in dup)
        bytes_dup = sum(size * n for size, n in self.counts.items() if size in dup)
        return {
            "files": files,
            "sizes": self.sizes_seen,
            "bytes": bytes_all,
            "files_to_hash": files_dup,
            "bytes_to_hash": bytes_dup,
            "files_skipped": files - files_dup,
            "bytes_skipped": bytes_all - bytes_dup,
        }
