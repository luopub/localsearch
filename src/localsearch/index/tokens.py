r"""FTS5 的预分词：**喂进去的和查出来的必须是同一套切法**（P4，`F4-01` 起共用）。

`D10` 的 `unicode61` 对中文**一个汉字也不切**——"北京大学的研究生前来报到"整句是一个
token（`M9` 实测，`tools/probe_deps.py` 里有原始读数）。所以中文要能按 2 字词搜到，
入库前就得把 CJK 段落切成空格分隔的词。这个模块就是那一刀。

本模块里的每一个数字都是 `tools/bench_tokenize.py` 量出来的（读数进 `PROGRESS.md` §3
的 `E38`），不是推理。第一版文档里的对照表是**凭印象写的**，真跑一遍就对不上——
比如 `前来报到` 被切成了 `前来 · 报 · 到`（不是 `报到`）。凡是这类"我以为 jieba 会
怎么切"的句子，都以探针输出为准。

------------------------------------------------------------------------------
一、索引侧用 `cut_for_search`（精确模式召回不够）
------------------------------------------------------------------------------

`E38` 的实测（16 条真实形状的文件名 + 路径，156 条"文件名里连续的 2/3 个汉字"查询，
真阳性按**原名字符串包含**机械判定）：

| 索引侧切法 | 微召回 | 一条都没找到的查询 |
|---|---|---|
| `jieba.cut` 精确模式 | **45.2%** | 84 / 156 |
| `jieba.cut_for_search` | **75.3%** | 40 / 156 |

原因是 `cut_for_search` 把长词连同它的 2/3 字子串一起倒出来：

| 原文 | `cut` | `cut_for_search` |
|---|---|---|
| `财务报表.xlsx` | `财务报表 · . · xlsx` | `财务 · 报表 · 财务报表 · . · xlsx` |
| `会议纪要-第3次.docx` | `会议纪要 · - · 第 · 3 · 次 · . · docx` | `会议 · 纪要 · 会议纪要 · - · 第 · 3 · 次 · . · docx` |
| `本地离线全盘全文搜索需求说明.docx` | `本地 · 离线 · … · 说明 · . · docx` | **与 cut 完全一致** |

第三行值得单独看一眼：**它不是万能的**，只会帮到"被切成一个长词"的那些（`财务报表`、
`会议纪要`）；本来就切成 2 字词的一句话，它一个字也不多切。

------------------------------------------------------------------------------
二、再加一层"相邻汉字的 2-gram"——这一层把召回从 75% 推到 99%
------------------------------------------------------------------------------

`cut_for_search` 补不上**跨词缝**：`财务报表` 切出 `财务` / `报表`，而 **`务报` 不在
里面**；`前来报到` 被切成 `报` / `到`，**`报到` 也不在里面**。用户敲的 2 字查询正好
落在缝上时，词法索引就是够不到——这是它 26% 查询全落空的那部分。

`E38` 的实测：索引里**再加上原文中相邻汉字的全部 2-gram**（不依赖词典），

| 索引侧 | 微召回 | 一条都没找到 |
|---|---|---|
| `cut_for_search` | 75.3% | 40 / 156 |
| `cut` + 2-gram | 98.2% | 3 / 156 |
| **`cut_for_search` + 2-gram** | **98.8%** | **2 / 156** |

剩下那 2 条（`文搜`、`科生培`）是"查询自己的精确切分与 2-gram 对不上"造成的：
`文搜` 被切成 `文` / `搜` 两个单字，丢掉单字之后**一个 token 都不剩**。这是残留的
下限，记在 P4「遗留」里；不要为它再加一层 3-gram，`E38` 显示 3 字窗口的召回本来就
是被 2-gram 覆盖之后才达标的。

⚠ `cut` + 2-gram 与 `cut_for_search` + 2-gram 只差 0.6 个点（1 条查询），而
`cut_for_search` 是**包含** `cut` 的（它一个词都不少切），所以取大的那个：
**索引侧 = `cut_for_search` + 相邻汉字 2-gram**。

------------------------------------------------------------------------------
三、2-gram 只给"名/路径"这一层，**不给正文**
------------------------------------------------------------------------------

`E38` 同时量了代价（token 数 = 落盘量）：

| 语料 | `cut` | `search` | `search` + 2-gram |
|---|---|---|---|
| 16 条名字 + 路径 | 121 | 146（1.21×） | **241（1.99×）** |
| 4396 字中文正文 | 2429 | 2667（1.10×） | **6713（2.76×）** |

正文那一列是关键：2-gram 让正文的 FTS 落盘量涨到 **2.76 倍**，而它的收益是
**没测过的**——`E38` 那 98.8% 量的是"用户敲文件名的一个碎片"，正文检索打的是词，
不是碎片（`财务报表` 里的 `报表` 由 `cut_for_search` 就够了）。

所以：

* `files_fts`（Tier0，文件名 + 路径）→ `tokenize(text, bigrams=True)`。名字短、总量小，
  而 `A8` 要的正是"按文件名搜到"，这 1.99 倍买到了 75% → 99%。
* `chunks_fts`（Tier1，正文）→ `tokenize(text, bigrams=False)`。2.76 倍的落盘量买一个
  没实测过的收益，不划算；等 P5 有了真实的正文查询再回头量。

`bigrams` **故意没有默认值**（与 `chunk/sliding.py` 那三个数值参数同一个理由）：
"这一列要不要 2-gram"是个必须每次想一遍的决定，给它一个默认值就等于让它默认做对。

------------------------------------------------------------------------------
四、查询侧用 `cut`（精确模式），并丢掉单字汉字
------------------------------------------------------------------------------

**查询侧不用 `cut_for_search`**，虽然 `E38` 里两者召回一模一样（75.3% / 75.3%）：
多出来的 token 在 AND 语义下**只能让结果变少**，不可能多找到东西，所以它是纯风险。
`E38` 里 156 条查询有 7 条两种切法的 token 集合不同，这一批里恰好没有伤到召回——
"这一次没伤到"不是理由，单调性才是。（`search+2g` 那一行也印证了这点：查询侧同样
是 75.3% → 98.8%，与查询侧用哪种切法无关。）

**丢掉单字汉字**（`的` / `了` / `在`），前提是丢完还有别的 token。AND 下同样是一个字
掐死整条查询：查询"项目的报表"要求文档里同时有 `项目`、`的`、`报表`，而
`项目报表.xlsx` 里**没有 `的`**。`E38` 的实测是这一条最值钱的数字：

| 索引侧 | 丢单字 | 微召回 |
|---|---|---|
| `cut_for_search` | 不丢 | 36.1% |
| `cut_for_search` | **丢** | **75.3%** |
| `cut_for_search` + 2-gram | 不丢 | 58.4% |
| `cut_for_search` + 2-gram | **丢** | **98.8%** |

全字都是单字时（用户真的在搜"书"）一个也不丢，否则查询会变成空的。单字 **ASCII**
不丢：`a.txt` 里的 `a` 是用户明确打出来的东西。索引侧不跟着丢——索引侧丢掉的词就再
也搜不到了，而单字在正文里是有意义的。

------------------------------------------------------------------------------
五、`OR` 兜底：量过了，**不采用**
------------------------------------------------------------------------------

曾经打算"AND 落空就用 OR 再查一遍"。`E38` 的读数把它否掉了：在 156 条查询上，
OR 兜底让微召回从 75.3% 变成 **75.3%**（一条都没多找回来），触发 40 次，其中**每一次
都返回 0 条**——因为那 40 条的 token 在索引里**一个都没有**，OR 也变不出来。

更糟的是它在真实规模上的失败形态：AND 返回 0 条时改用 OR，用户看到的是**一堆排序
靠后的不相关结果**，而他分不清那是"没有匹配"还是"匹配得不好"。这个项目在别处明确
反对这种行为（`D10` 的降级必须**显式标注**），所以宁可老实回 0 条。

`or_expr()` 仍然留在这里，因为**探针要用它做对照**（"不采用"这个结论将来要在真实的
正文查询上复验）；`sqlite_store.py` 不用它。
"""

from __future__ import annotations

import logging
import re
from collections.abc import Sequence

# jieba 0.42.1 在 py3.12 下导入时抛若干条 `SyntaxWarning`（旧式正则），并且会往
# stderr 打 "Building prefix dict ..." 之类的闲聊。两者都会污染 CLI 输出，而真的错误
# 会淹在里面。警告那一条已经在 `core/logging.install_warning_filters()` 里按模块压掉了
# （它挂在 `main()` 的日志装配里）；这里压的是**它自己的 logger**——那是另一条路径，
# 警告过滤器管不着。级别设成 ERROR 而不是 CRITICAL：jieba 真要报错还是要看得见的。
import jieba

jieba.setLogLevel(logging.ERROR)

__all__ = [
    "HAN",
    "SEPARATOR",
    "and_expr",
    "han_bigrams",
    "index_tokens",
    "keep_token",
    "or_expr",
    "query_tokens",
    "tokenize",
]

#: token 之间用什么隔开。空格是 FTS5 的分词边界，也是 `unicode61` 认的分隔符——
#: 换成别的（比如 `,`）同样能分开，但 `unicode61` 会把它当标点丢掉、存不进索引，
#: 而这一列是**要能直接 `sqlite3` 打开看的**（排障时第一件想做的事）。
SEPARATOR = " "

#: 汉字（含扩展区与兼容区）。两处用它：切 2-gram 时判"这一对是不是汉字"，
#: 查询侧判"这个单字 token 要不要丢"。
HAN = re.compile(r"[\u3400-\u4dbf\u4e00-\u9fff\uf900-\ufaff]")

#: 一个 token 至少要有一个"字"字符才留下。判据取 `\w`，与 `unicode61` 认定 token
#: 字符的口径对齐（字母、数字、汉字都算），纯标点一律丢。
#: ⚠ `_` **是** `\w`、但**不是** `unicode61` 的词内字符（它把 `_` 当分隔符），
#: 所以 `my_var` 会先在库里被拆成 `my` + `var`。查询侧同样要过 `unicode61`，
#: 一个 `my_var` 查询也会被拆成 `my` AND `var`——两边一致，因此不影响命中。
_HAS_WORD_CHAR = re.compile(r"\w", re.UNICODE)


def keep_token(token: str) -> bool:
    """这个 token 里有没有"字"字符（纯标点/空白的丢掉）。"""
    return bool(_HAS_WORD_CHAR.search(token))


def han_bigrams(text: str) -> list[str]:
    r"""原文里**相邻两个汉字**的全部组合（跨词边界也照取，重复的照留）。

    "重复的照留"是量出来的选择：去重只在文本自身重复时才省东西，而它会让"2-gram 让
    落盘量涨多少"这个数**依赖语料**（`E38` 的正文样本把 25 句话重复六遍，去重后
    增量从 2.76× 掉到 1.30×——那是样本的性质）。真实正文里去重只省 0.8%，
    不值得换一个会骗人的读数。

    ⚠ 只取**两个都是汉字**的相邻对：`D:\work\项目\2024` 里的 `目\`、`4年` 这种一边是
    分隔符或数字的组合一律不取——它们既不是词，也没有人会这样搜。
    """
    out: list[str] = []
    for i in range(len(text) - 1):
        pair = text[i : i + 2]
        if HAN.match(pair[0]) and HAN.match(pair[1]):
            out.append(pair)
    return out


def index_tokens(text: str, *, bigrams: bool) -> list[str]:
    """索引侧：一段文本 → 该存进 FTS 的 token 列表。

    小写在切分**之前**做：`unicode61` 自己也会折叠 ASCII 大小写，显式做一遍只是让
    落库的那一列可读（`SELECT name_tok FROM files_fts` 时看到的是小写）。
    """
    if not text:
        return []
    lowered = text.lower()
    tokens = [t for t in jieba.cut_for_search(lowered) if keep_token(t)]
    if bigrams:
        tokens += han_bigrams(lowered)
    return tokens


def tokenize(text: str, *, bigrams: bool) -> str:
    """索引侧的落库形态：token 用空格连起来。空文本给空串（不是 `None`）。"""
    return SEPARATOR.join(index_tokens(text, bigrams=bigrams))


def query_tokens(query: str) -> list[str]:
    """查询侧：用户敲的那串 → token 列表（精确模式 + 丢单字汉字，见模块文档四）。"""
    if not query:
        return []
    raw = [t for t in jieba.cut(query.lower()) if keep_token(t)]
    trimmed = [t for t in raw if not (len(t) == 1 and HAN.match(t))]
    # 全是单字时退回丢之前的列表：用户真的在搜"书"，丢掉它等于什么都不搜。
    return trimmed or raw


def _quote(token: str) -> str:
    """一个 token → FTS5 里的字符串字面量。

    加引号不是为了好看，是**为了不被当成语法**：`AND` / `OR` / `NOT` / `NEAR` /
    `*` / `(` 在 MATCH 表达式里都有含义，一个叫 `and.txt` 的文件名会让查询直接抛
    `fts5: syntax error`。引号内的一切都是字面量，这是唯一不用维护"保留字名单"的
    做法——黑名单早晚会漏。

    内部的双引号按 FTS5 的规矩写成两个（`"` → `""`）。走不到这一步（`keep_token`
    已经把标点滤掉了），但留着：这个函数将来被别处调用时，"引号转义"不该是调用方
    的责任。
    """
    return '"' + token.replace('"', '""') + '"'


def and_expr(tokens: Sequence[str]) -> str | None:
    """隐式 AND 的 MATCH 表达式；没有 token 时返回 `None`（调用方据此**不查**）。

    FTS5 里 `a b c` 就是 "a 且 b 且 c"——**不需要写 `AND`**，引号之间留空格即可。
    返回 `None` 而不是空串：空串会让 `MATCH ''` 抛语法错，而"没有可用的 token"
    与"匹配不到任何东西"是两件事，调用方要能分开处理（前者是用户输入里没有可搜的
    东西，后者是一个正常但空的结果）。
    """
    if not tokens:
        return None
    return SEPARATOR.join(_quote(t) for t in tokens)


def or_expr(tokens: Sequence[str]) -> str | None:
    """显式 OR 的 MATCH 表达式；没有 token 时返回 `None`。

    ⚠ **`sqlite_store.py` 不用它**，理由见模块文档五（`E38` 实测：买不到召回，
    而且它的失败形态是"静默给出不相关结果"）。留着是给 `tools/bench_tokenize.py`
    做对照，以及给将来在真实正文查询上的复验。
    """
    if not tokens:
        return None
    return " OR ".join(_quote(t) for t in tokens)
