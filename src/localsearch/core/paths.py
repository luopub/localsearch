r"""路径交给 Win32 之前的一道转换：保留设备名的绕行（P2 / `F2-02`）。

这一层只回答一个问题：**这条路径要不要换成 `\\?\` 写法？** 要就换，不要就原样还回去。
它不含任何扫描语义，也不碰盘——除了测试，它一个系统调用都不发。

------------------------------------------------------------------------------
为什么会有这一层
------------------------------------------------------------------------------

`F2-02` 的真机核对（2026-10-15，管理员终端，`D:/work`）判出 2 条不一致，查下来是
Windows 的**保留设备名**：路径的最后一段若是 `nul`，Win32 的**名字解析**会把它解析
成 `\\.\NUL` **设备**，于是同一个文件对不同的问法给出不同答案：

| 问法 | `D:/work/test/opencode/nul`（真文件，83 字节） |
|---|---|
| `os.scandir` 的枚举（属性随枚举带回） | 真文件：属性 `0x20`、大小 83 |
| `os.stat(原样)` | **成功**，但报 `st_ino=0 / 大小=0 / 属性=0` —— 那是 NUL 设备 |
| `GetFileAttributesExW(原样)` | **失败 `winerror=87`**（`ERROR_INVALID_PARAMETER`） |
| `open(原样)` | **成功**，读到 **0 字节**（设备读到 EOF，不是文件内容） |
| 上面三样加 `\\?\` 前缀 | 全部指到那个真文件（`st_ino` 是它的 FRN、83 字节、内容对） |

`\\?\` 前缀的用处正是这个：它把路径**直接交给内核**，跳过 Win32 的名字解析。

**三种失败里有两种是静默的**——`os.stat` 与 `open` 都会"成功"，一个给出 `st_ino=0`
的假属性，一个给出 0 字节的假内容。这正是项目明令禁止的"静默返回不完整结果"
（`CLAUDE.md` 的「分级就绪」一条）。所以这一层是**先判定、再转换**，而不是"调用
失败了再重试"：**重试救不了 `open`**，它根本不失败。

------------------------------------------------------------------------------
范围：实测中招的只有 `nul` 一族
------------------------------------------------------------------------------

2026-10-15 在本机（Win11 10.0.26300 / NTFS / D:）**真建**了下面这些名字再逐个问
（`\\?\` 是唯一建得出来的办法）。原样路径的读数：

| 名字 | `os.stat(原样)` | `open(原样)` 读到的 |
|---|---|---|
| `nul` / `NUL` | 设备（`st_ino 0`、大小 0） | **0 字节** |
| `nul.` / `nul ` / `nul..` | 设备（同上） | **0 字节** |
| `con` `prn` `aux` `com1` `com9` `lpt1` `lpt9` | 真文件 | 真内容 |
| `con.txt` `prn.txt` `aux.txt` `com1.txt` `lpt1.txt` | 真文件 | 真内容 |
| `nul.txt` `nul.map` | 真文件 | 真内容 |
| `nulx` `a.nul` `normal.txt` | 真文件 | 真内容 |
| `…\nul\inner.txt`（设备名在**中间**一层） | 真文件 | 真内容 |

三条从这里读出来的结论，直接决定本模块的形状：

1. **只有 `nul` 一族真的中招**，而且**尾部的点与空格也算**（Win32 的归一化会先把
   它们剥掉，`nul.` 于是正好落到设备上）。DOS 时代那条"`con`/`prn`/`aux`/`com1`…
   都算设备名、带扩展名也算"的老规则，在这台机器的这一批 API 上**不成立**。
2. **设备名在中间一层不影响**（`…\nul\inner.txt` 读得好好的），所以谓词**只看最后
   一段**。这一条是有实测撑着的，不是图省事：热路径上每跳一次多解析几段是白花钱。
3. **设备名可以是真目录**（`\\?\` 下建得出来）：`os.scandir(原样)` 列得出来，
   但 `Path.is_dir()` 会返回 **False**（它走 `os.stat`，问到的是设备）——
   所以"问真相"的那几个调用点里，根可达性检查也在名单上。

**谓词仍然按 DOS 设备名的全集写**（`DEVICE_NAMES`），尽管今天只有 `nul` 真的中招。
理由是不对称：`\\?\` 对上面**每一个**名字都实测指到了真文件（22 个名字逐个试过），
所以**写宽只会多绕一次、不会指错**；写窄则意味着换一个 Windows 版本或换一批 API
就静默失手——那正是这一层要防的事。

------------------------------------------------------------------------------
边界：宁可原样返回，也不猜
------------------------------------------------------------------------------

`\\?\` 不只是"加个前缀"，它会**关掉** Win32 的归一化：`.` 与 `..` 不再被解释、
正斜杠不再当反斜杠、尾部的点与空格不再被剥掉，而且它只认**绝对路径**。所以本模块
只在形态说得清的时候转换，说不清就**原样返回**：

| 形态 | 处置 | 为什么 |
|---|---|---|
| 相对路径 `sub/nul` | 不转 | `\\?\` 要求绝对路径 |
| 盘符相对 `C:nul` | 不转 | 同上 |
| 含 `.` 或 `..` 段 | 不转 | 关了归一化之后 `..` 会被当成字面目录名，转过去只是换个错法 |
| 已经是 `\\?\` 或 `\\.\` | 不转（**不许重复加**） | `\\.\` 是设备命名空间，加一层 `\\?\` 反而指错 |
| UNC `\\srv\share\nul` | 转成 `\\?\UNC\srv\share\nul` | ⚠ **本机没有可用的共享，这一支未实测**，只有纯字符串的单测 |

"不转"的含义是**保持现状**，不是"更安全"：一条相对路径里的 `nul` 今天怎么错，不转
之后还是怎么错。本仓库里能走到这里的路径都是绝对路径（两个后端都用"父 + 名字"拼
出来），所以这一栏是防"将来有人从别处喂进来一条没想过的形状"。

------------------------------------------------------------------------------
怎么用（只有一条规则）
------------------------------------------------------------------------------

**把路径交给系统去问真相的地方，一律先过 `extended_path`；把路径记住、显示、落库
的地方，一律用原样。**

- 问真相：`GetFileAttributesExW` / `os.stat` / `open` / `os.scandir`
- 原样：`ScanEntry.path`、错误账里的路径、抛出异常时的 `filename`

按这条规则逐个过了一遍的调用点（`F2-02` 收尾时核过）：

| 调用点 | 问的是什么 |
|---|---|
| `ingest/ntfs.py` 的 `attributes_of` | 大小与时间（`F2-02` 抓出问题的那一处） |
| `ingest/fingerprint.py` 的 `content_hash` | 正文（静默读 0 字节的那一处） |
| `ingest/fingerprint.py` 的 `quick_sig_of` | `stat` 指纹 |
| `ingest/scanner_mft.py` 的 `_handle` | reparse 那支的 `os.stat`（要 tag） |
| `ingest/scanner_mft.py` 的 `_prepare_root` | 根的存在 / 是不是目录 / FRN |
| `ingest/scanner_scandir.py` 的 `_scan_root` | 同上（两个后端必须逐条同义） |

**已知不需要绕的一处**：`scanner_scandir._walk` 的 `os.scandir(目录)`——实测
设备名的目录也能原样列出来（`\\?\` 建出来的 `…\nul`，原样 `scandir` 返回
`['inner.txt']`），所以下潜那一步不动。

**加一处就要在这一行里补一处。** 这张表是给后来人看的清单，本模块只此一份。

------------------------------------------------------------------------------
代价
------------------------------------------------------------------------------

每次调用是几次字符串操作加一次 `frozenset` 查表，**不碰盘**：2026-10-15 实测
**0.98 µs/次**（`tools/bench_paths.py`，n=2,000 条合成路径，7 轮中位数，各轮
0.98 0.97 0.98 0.98 0.98 0.99 0.98）。绝大多数路径在"最后一段不是设备名"那一步
就返回了，转换代码根本不执行。

折到整轮：`D:/work` 那一轮是 1,028,697 次，**多花约 1.01 s**——占该轮 MFT 整轮
163.37 s 的 **0.6%**、占 `scandir` 整轮 51.85 s 的 **1.9%**。⚠ 别按"占
`attributes_of` 的百分之十几"去读（5.3 µs 那个数）：补属性本身只占整轮 5.5 s，
两条数放一起比会显得这一层很贵。

第一版写成了两圈逐字符的 Python 层循环（数下标找最后一段），同一批路径实测
**1.54 µs/次**，是现在的 **1.57 倍**。换成 `rstrip` + `rfind` 两个 C 层调用就到
0.98，再往下压要到 0.5 量级得牺牲可读性，换来的只有 0.6 s，不值。

⚠ **这一节的数换过一次来源**：0.98 / 1.54 出自入库的 `tools/bench_paths.py`；
此前写的 0.91 / 1.61 / 1.8 倍来自一份**没入库的一次性内联脚本**，语料也不同
（那是真路径，脚本没了）。两份读数差得不多、结论一样，但按"同一件事只允许有
一个真相来源"，这里只留能复跑的那一份。`E17` 那条教训适用于此：这类数字要连
当时的机器负载一起看，小数位没有意义。
"""

from __future__ import annotations

import os

#: DOS 的保留设备名。**不含** `COM0` / `LPT0`：它们不在老规则里，本机也没试过。
#: 比对的写法见 `_is_device_component`（取最后一段、剥掉尾部的点与空格、再取第一个
#: 点之前的部分、大写之后查这张表）。
DEVICE_NAMES = frozenset({
    "CON", "PRN", "AUX", "NUL",
    *(f"COM{i}" for i in range(1, 10)),
    *(f"LPT{i}" for i in range(1, 10)),
})

#: 已经是扩展写法的前缀。`\\.\` 是设备命名空间（`\\.\C:` 那种），它也算"已经有了"：
#: 往它前面再加 `\\?\` 会指到别处去。
_ALREADY = ("\\\\?\\", "\\\\.\\")


def extended_path(path: str | os.PathLike[str]) -> str:
    r"""这条路径该用什么写法交给系统：需要绕行时是 `\\?\` 形式，否则**原样返回**。

    调用的地方只管把返回值用掉——不需要绕的时候它与你传进去的是同一条字符串
    （不是副本，所以拿它当字典键也不会多花什么）。

    ⚠ **返回值只许用于系统调用，不许落库、不许显示**：`\\?\` 是 Win32 的实现细节，
    带前缀的路径进了 `ScanEntry.path` 或数据库，就会在下一次比较、拼接、去重时变成
    另一条路径。这条规则与模块文档末尾那张调用点清单是一回事。
    """
    text = os.fspath(path)
    if not isinstance(text, str):
        # 字节路径：`os.fspath` 只在传 `bytes` 时才走到这里，本仓库不使用，也不猜
        # 它的编码——原样还回去，让调用方按老规矩办事。
        return text
    if text.startswith(_ALREADY):
        return text
    if not _needs_extension(text):
        return text
    native = _to_native(text)
    if native is None:
        # 形态说不清（相对路径 / 盘符相对 / 含 `.` 或 `..` / 尾部剥完什么都不剩）。
        # **保持现状**，不猜：见模块文档的边界表。
        return text
    if native.startswith("\\\\"):
        return "\\\\?\\UNC\\" + native[2:]
    return "\\\\?\\" + native


def _needs_extension(text: str) -> bool:
    """最后一段是不是设备名。**只看最后一段**——中间一层是设备名不影响（实测）。

    尾部的分隔符先摘掉：`D:/x/nul/` 指的也是那个目录，它同样中招。

    ⚠ 这里**故意写成 `rstrip` + `rfind`**，而不是数着下标走两圈 Python 层循环：
    本函数在热路径上（一次全盘索引按条目数各调一次，`D:/work` 实测 102.9 万次）。
    两圈逐字符的循环实测 1.54 µs/次，换成两个 C 层调用之后是 0.98 µs/次，差 1.57 倍
    （`tools/bench_paths.py`，同一批 2,000 条路径，7 轮中位数）。
    """
    trimmed = text.rstrip("\\/")
    part = trimmed[max(trimmed.rfind("/"), trimmed.rfind("\\")) + 1:]
    return _is_device_component(part)


def _is_device_component(part: str) -> bool:
    """一段名字算不算设备名：`nul` / `NUL` / `nul.` / `nul ` / `nul.txt` 都算，
    `nulx` / `a.nul` / `..` 不算。

    两条比对前的处理都来自实测：尾部剥掉点与空格（`nul.` 原样路径确实中招），
    再取第一个点之前的部分（DOS 老规则比对的就是它）。
    """
    return part.rstrip(" .").partition(".")[0].upper() in DEVICE_NAMES


def _to_native(text: str) -> str | None:
    r"""换成 `\\?\` 认的写法，形态说不清就返回 `None`（调用方原样返回）。

    只做两件事：正斜杠换反斜杠、摘掉尾部分隔符。**不做词法归一化**——把 `..` 按
    字面消掉是错的（软链接下的 `..` 与字面层级不是一回事），而 `\\?\` 又不认 `..`，
    所以含 `.`/`..` 的路径一律拒绝，不试图"帮它修好"。
    """
    native = text.replace("/", "\\").rstrip("\\")
    if len(native) < 3:
        return None                      # `D:` / `\\` / `C`：说不清
    if native.startswith("\\\\"):
        rest = native[2:]                # UNC：`server\share\…`
    elif native[1] == ":":
        if native[2] != "\\":
            return None                  # 盘符相对：`C:nul`
        rest = native[3:]
    else:
        return None                      # 相对路径
    if any(part in (".", "..") for part in rest.split("\\")):
        return None
    return native
