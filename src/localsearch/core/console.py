r"""输出面的多字节安全：**编不了就降级，不许崩**。

------------------------------------------------------------------------------
为什么要有这个模块
------------------------------------------------------------------------------

`E16` 那条（本机默认控制台是代码页 936，`print` 里出现 GBK 编不了的字符会当场
`UnicodeEncodeError`）一直是**靠纪律**守着的：每个脚本自己保证打印路径上只用 GBK
认得的字符——`0dcb708` 就是这么修 `scan_report.py` 的，顺手把用法里那句「必须设
`PYTHONIOENCODING=utf-8`」删掉了。

2026-10-16 实测发现这条纪律有两处够不着，两处都不是"再仔细点"能解决的：

**1. 它只在管道 / 重定向下爆。** 真控制台里 Python 用 UTF-8（PEP 528），`⚠` 打得
出来；一旦 `> 报告.txt`、`| tail`、或子进程里 `capture_output=True`，Python 改用
ANSI 代码页（936），同一行当场崩。所以**「我在终端里跑过，没事」不是证据**——本机
默认环境下 `uv run lsearch index --help` 打得出来，`uv run lsearch index --help >
x.txt` 退出码 1（`E37` 的实测之一）。

**2. 纪律管不到文档串。** `lsearch index --help`、`tools/scan_report.py --help` 崩在
click / argparse **打印命令文档串**的时候，而那些文档串里的 `⚠` 是项目写作习惯，
`⚠` 在本仓 `.py` 文件里共 **162 处**（2026-10-16 实测：`src/` 83 处、20 个文件；
`tools/` 79 处），要靠逐个删掉不现实，也没人会在新写一段文档时想起来这条。

最坏的一例是 `tools/check_mutations.py`：**变体全部抓到的成功跑法，最后一行带
`⚠`，于是退出码 1**——而它的退出码就是它的结论，等于结论反过来。它之前跑绿过，
只是因为那几次的 stdout 恰好是真控制台。

------------------------------------------------------------------------------
做法：只改 errors，不改 encoding
------------------------------------------------------------------------------

把 `sys.stdout` / `sys.stderr` 的 `errors` 设成 `replace`：

- 编码仍是本机编码（GBK），**中文一个不少**，`> 报告.txt` 之后在 GBK 编辑器里照旧
  看得懂；
- 编不了的字符（`⚠` / `✔` / `✘` / `µ`）印成 `?`——**难看，但难看出现在本该有结论的
  那一行上，而不是把这一整轮输出连同结论一起吃掉**。

**不改成 UTF-8**：`> 报告.txt` 之后用记事本 / GBK 编辑器打开会整篇乱码；而真控制台
本来就走 UTF-8（PEP 528）。改编码只是把一处不一致换成另一处。

**不要求调用方先设 `PYTHONIOENCODING`**：那是让用户替程序背这条纪律，
`0dcb708` 已经否掉过一次。

------------------------------------------------------------------------------
谁该调、在哪调
------------------------------------------------------------------------------

**每个有输出面的入口都调一次**，位置要早到「帮助打印之前」：

- `src/localsearch/cli/main.py` 在 `main()` 的第一行——`lsearch <子命令> --help`
  打印帮助发生在回调之前，挂在 Typer 回调里**来不及**；
- `tools/*.py` 在各自的 `main()`（没有 `main()` 的写进 `__main__` 块）第一行。

**幂等**，重复调用无所谓；对没有 `reconfigure` 的流（pytest 的捕获对象、
`pythonw` 下的 `None`、已经被关掉的流）直接跳过，所以不影响测试捕获，也不影响把
`stdout` 换成 `StringIO` 的调用方。

「打印路径上只用 GBK 认得的字符」这条纪律**不撤销**（`E16` 仍成立，`?` 终究是
降级）：能避免引入 `⚠` 的地方仍然避免（`probe_ooxml_time.py` 就是这么改的）。这一
层是**兜底**，不是许可证。
"""

from __future__ import annotations

import sys
from typing import Any


def use_safe_output() -> None:
    """让 `stdout` / `stderr` 在编不出某个字符时降级成 `?`，而不是抛异常。

    只动 `errors`，不动 `encoding`：理由见模块文档。幂等；没有 `reconfigure` 的流
    会被跳过（pytest 的捕获对象、`pythonw` 下的 `None`），已经关掉的流也不会炸。
    """
    for stream in (sys.stdout, sys.stderr):
        reconfigure: Any = getattr(stream, "reconfigure", None)
        if reconfigure is None:  # 捕获对象 / None：不是我们能配的文本流
            continue
        try:
            reconfigure(errors="replace")
        except (ValueError, OSError):  # 流已关闭或不可配置
            continue
