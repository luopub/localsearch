"""跨层共用的数据形态：一个文件提出来是什么、切成片是什么（P3）。

这一层只有**形状**，没有行为，也不碰盘：`extract/`、`chunk/`、将来的 `index/` 与
`search/` 全都按这两种类型对接，所以它们不能长在任何一个消费者里。这正是
`core/__init__.py` 那句"跨层共用的数据模型"的落点。

（P2 的 `ScanEntry` 不在这里，它在 `ingest/base.py`——那是 P2 的既成事实，不是本模块
要顺手搬的东西。两边的差别是真实的：扫描条目带排除规则的判定与理由，属于扫描层
自己的词汇；而"提取出的一段正文"与"切开的一片"是下游所有层共用的。搬家会把 P2
那批测试全部拉进无关的改动里，收益是零。)

------------------------------------------------------------------------------
`modality` 在 v1 全是 `text`，这是刻意的
------------------------------------------------------------------------------

字段现在就存在（计划 §4.2 的扩展点要求），但 **v1 的四个提取器一律填 `text`**，
包括 `media_meta`——它出的是"文件名 + EXIF/ID3"这些**字**，不是图片本身。计划 §1.3
把"图片/音频/视频的**内容**向量化"划在 v1 之外，所以那些切片进的是文本向量库；
填成 `image` 会让 `chunks.modality` 说谎（它其实是文本），而将来 P9 真做视觉向量时，
媒体类型该由**那时的**提取器决定，不是今天先在元数据文本上盖一个提前的章。

媒体自己的类别（照片 / 音频 / 视频）记在 `meta["kind"]` 里，需要的时候读得到，
但它**不参与**任何线上下载路径或检索逻辑。
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any

# ==============================================================================
# 一个文件提取出来的东西
# ==============================================================================


@dataclass(frozen=True, slots=True)
class ExtractedDoc:
    """一个文件的正文，以及跟着它一起出来的附着信息。

    字段之间只有一条硬约定：**`text` 是切片的唯一输入**。`chunk/` 只看 `text`，
    所有偏移（`Chunk.char_start` / `char_end`）都指的是**在 `text` 上的下标**，
    半开区间 `[start, end)`。所以任何"为了让下游好处理"而改动 `text` 的想法，
    都要先想清楚它会不会让偏移对不上——`plaintext.py` 因此**故意不归一化换行符**。

    `truncated` 是**提取层**的截断（正文太长、格式结构太深、附件层数到顶），与
    `Chunk` 那片"超过 200 片上限"的截断（`D8`）是两件事，两个标志各自记各自的。
    混成一个会让"这个文件是正文缺了还是切片缺了"永远说不清。
    """

    text: str
    #: 文档自己的标题（docx 的核心属性、HTML 的 `<title>`、邮件的 `Subject`）。
    #: **纯文本一律 `None`**——文件名叫什么不是文档的标题，而嵌入时要的
    #: `title: {t} | text: {c}` 前缀在无标题时有明确的写法（`title: none`，`M3`）。
    #: 用文件名去顶替它会让"标题"这个字段失去意义，也会让同一份内容改名之后
    #: 算出不同的向量（`A9` 的去重是按内容算的，但向量缓存 `embed_cache` 的键是
    #: 最终喂进去的文本——前缀里混进文件名，同一份内容就再也复用不上向量了）。
    title: str | None = None
    #: 提取器顺手拿到的结构化信息（编码、页数、EXIF、作者、`kind`……）。
    #: **只给人看与排查用**，不参与检索、不参与偏移计算。键一律是稳定的英文短名。
    meta: dict[str, Any] = field(default_factory=dict)
    #: 见模块文档：v1 全是 `text`。
    modality: str = "text"
    #: 是哪个提取器出的（`PlaintextExtractor` 的 `name`）。排查"这个文件的正文为什么
    #: 长这样"时，第一个要问的就是它——四个提取器的失败形态完全不同。
    source: str = ""
    #: 提取层截断过（见类文档第一段）。
    truncated: bool = False
    #: 提取过程中**没到失败、但也不该静默吞掉**的事（编码是猜的、某一段解析不动被跳过、
    #: 附件超深度没展开……）。空元组 = 一切正常。
    #:
    #: 用元组而不是列表：这个对象是 frozen 的，一个可变的 `warnings` 会让它看起来
    #: 只读、实际谁都能往里塞——而这正是"静默"的来源。
    warnings: tuple[str, ...] = ()

    @property
    def char_count(self) -> int:
        return len(self.text)

    @property
    def is_empty(self) -> bool:
        """正文是空的（全空白也算）。

        **它不等于失败**：一个真的 0 字节文件本来就该产出空正文。要小心的是另一头——
        非空文件读出空正文（`F2-02` 抓出的保留设备名就是这种，`E27`），那种要由
        提取器**显式报错**，不能靠这个属性悄悄放过。`plaintext.py` 里有一条专门管它。
        """
        return not self.text.strip()


# ==============================================================================
# 切开的一片
# ==============================================================================


@dataclass(frozen=True, slots=True)
class Chunk:
    """`ExtractedDoc.text` 上的一段，带它在原文里的位置。

    `ord` 从 **0** 开始，在同一个文档内连续。它对应 `chunks.ord`（计划 §4.4），
    而 `(blob_id, ord)` 是那张表上的索引——所以**同一个 blob 的切片顺序必须稳定**：
    同一段文本今天切出 5 片、明天切出 6 片，`embed_cache` 里那些向量的复用就全废了，
    而这正是 `A9` 要省的钱。

    `n_tokens` 是**切分时**数出来的 token 数。⚠ 它的口径取决于 `chunk/sliding.py`
    接到的计数器：默认是字符启发式（一个估计值），`P5` 会换成嵌入器自己的 tokenizer。
    所以它**不能**拿来当"这段文本嵌进去要占多少上下文"的保证——要精确值只能问
    那个真正的 tokenizer。
    """

    ord: int
    text: str
    #: 在 `ExtractedDoc.text` 上的半开区间 `[char_start, char_end)`。
    #: 相邻两片因重叠而**共享**一段文本时，前一片的 `char_end` 大于后一片的
    #: `char_start`——这是重叠的定义，不是错误。
    char_start: int
    char_end: int
    n_tokens: int
    #: 这一片是 `D8` 的"已截断"标注片（正文太长、只留了表头与统计摘要那一片）。
    #: 它**不是**原文的一段，而是一句说明——所以 `char_start` / `char_end` 对它没有
    #: 意义，一律写 0，并且**不要**拿它去原文里取片段（`ord` 最大的那片才可能是它）。
    truncated: bool = False

    @property
    def is_placeholder(self) -> bool:
        """这一片不是原文（见 `truncated` 的说明）。给高亮与 `snippet` 用。"""
        return self.truncated
